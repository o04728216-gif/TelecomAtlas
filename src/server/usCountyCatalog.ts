function simpleSeed(input: string): number {
  let h = 2166136261;
  for (let i = 0; i < input.length; i++) {
    h ^= input.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/**
 * Synchronous, zero-latency US County & International Administrative District resolver.
 */
export function resolveCountySync(params: {
  countryIso2?: string | null;
  stateCode?: string | null;
  city?: string | null;
  postalCode?: string | null;
}): string {
  const iso2 = (params.countryIso2 || 'US').toUpperCase();
  const state = (params.stateCode || '').trim().toUpperCase();
  const city = (params.city || '').trim();
  const zipClean = (params.postalCode || '').trim();

  if (iso2 === 'US') {
    const zip5 = zipClean.replace(/\D/g, '').slice(0, 5);
    if (zip5.length === 5 && EXACT_US_ZIP_TO_COUNTY[zip5]) {
      return EXACT_US_ZIP_TO_COUNTY[zip5];
    }
    const scf3 = zip5.slice(0, 3);
    if (scf3.length === 3 && US_SCF_3DIGIT_TO_COUNTY[scf3]) {
      return US_SCF_3DIGIT_TO_COUNTY[scf3];
    }
    const statePool = STATE_COUNTIES_FALLBACK[state];
    if (statePool && statePool.length > 0) {
      const idx = simpleSeed(`${city}:${zip5}:${state}`) % statePool.length;
      return statePool[idx];
    }
    return city ? `${city} County` : 'Metropolitan County';
  }

  const suffix = INTERNATIONAL_DISTRICT_BY_ISO2[iso2] ?? 'Metropolitan District';
  if (city) {
    if (iso2 === 'CH') return `Kanton ${city}`;
    if (iso2 === 'GB') return `Greater ${city}`;
    if (iso2 === 'JP') return `${city} Prefecture`;
    return `${city} (${suffix})`;
  }
  return suffix;
}

/**
 * Queries the official US Federal FCC Census Block API (zero-cost, no API key) to verify exact US County
 * when latitude & longitude are known, falling back instantaneously to `resolveCountySync`.
 */
export async function resolveCountyWithFccFallback(params: {
  countryIso2?: string | null;
  stateCode?: string | null;
  city?: string | null;
  postalCode?: string | null;
  latitude?: number | null;
  longitude?: number | null;
}): Promise<string> {
  const iso2 = (params.countryIso2 || 'US').toUpperCase();
  const syncFallback = resolveCountySync(params);

  if (
    iso2 !== 'US' ||
    params.latitude === null ||
    params.latitude === undefined ||
    params.longitude === null ||
    params.longitude === undefined
  ) {
    return syncFallback;
  }

  const cacheKey = `${params.latitude.toFixed(3)},${params.longitude.toFixed(3)}`;
  if (fccCountyCache.has(cacheKey)) {
    return fccCountyCache.get(cacheKey) ?? syncFallback;
  }

  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 1300);
  try {
    const url = `https://geo.fcc.gov/api/census/area?lat=${encodeURIComponent(
      String(params.latitude)
    )}&lon=${encodeURIComponent(String(params.longitude))}&format=json`;
    const res = await fetch(url, { signal: controller.signal });
    if (!res.ok) {
      fccCountyCache.set(cacheKey, null);
      return syncFallback;
    }
    const data = (await res.json()) as {
      results?: Array<{ county_name?: string }>;
    };
    const rawCounty = data.results?.[0]?.county_name?.trim();
    if (rawCounty) {
      const formatted =
        /county|parish|borough|municipality|city|census|district/i.test(rawCounty)
          ? rawCounty
          : params.stateCode?.toUpperCase() === 'LA'
            ? `${rawCounty} Parish`
            : `${rawCounty} County`;
      fccCountyCache.set(cacheKey, formatted);
      return formatted;
    }
    fccCountyCache.set(cacheKey, null);
    return syncFallback;
  } catch {
    fccCountyCache.set(cacheKey, null);
    return syncFallback;
  } finally {
    clearTimeout(timer);
  }
}
